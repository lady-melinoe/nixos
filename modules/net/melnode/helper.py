"""melnode-helper: the glue between melnode and the rest of the host.

melnode itself only builds the mesh and creates one network device, whose neighbour table has an
entry (permanent, link address = the node's id) for every node it can reach; routes to a node go
via the node's address on that device. Everything the old melinoe-route daemon did *around* that
lives here instead:

  hook-create <peerid> <ifname> <gateway>
      melnode peerCreateHookBin: set up per-node policy routing (fwmark and
      table `table_base + peerid`) and register the node in the nft
      conntrack-pinning set/map (keyed by the sender's link address, `@ll,8,8`),
      then point the table's default route at the node's gateway address.
      Until then the table's default route is `unreachable`, so marked
      traffic never leaks out of another interface while the node is not
      set up.

  hook-destroy <peerid> <ifname> <gateway>
      melnode peerDestroyHookBin: undo the above (runs after the neighbour
      entry is gone).

  daemon
      Long-running. Every tick it:
        * advertises this node's prefixes (routes on vm-* interfaces,
          public IPs, extraRoutes) to melnode's control socket, and
          withdraws them when they disappear;
        * heals per-node state (rules/routes/nft entries) that the hooks set
          up but something else removed, e.g. an nftables reload flushing
          the runtime sets, and garbage-collects state for vanished nodes.

Config is a JSON file (--config), generated by modules/net/melnode.nix.
Only the standard library, `ip` and `nft` (on PATH) are used.
"""

from __future__ import annotations

import argparse
import http.client
import ipaddress
import json
import logging
import os
import signal
import socket
import subprocess
import sys
import threading
from dataclasses import dataclass, field

log = logging.getLogger("melnode-helper")

MAX_PEER_ID = 255

ROUTE_PROTO = "198"


@dataclass
class Config:
    node_id: int
    table_base: int
    interface: str
    control_socket: str
    pub_ips: list[str]
    extra_routes: list[str]
    vm_iface_prefix: str
    nft_family: str = "inet"
    nft_table: str = "mangle"
    nft_mark_set: str = "melinoe_peer_marks"
    nft_id_map: str = "melinoe_peer_ids"
    poll_interval: float = 2.0
    full_resync_ticks: int = 5

    @staticmethod
    def load(path: str) -> Config:
        with open(path) as f:
            return Config(**json.load(f))

    def table(self, peer_id: int) -> int:
        return self.table_base + peer_id

    def owns_table(self, table: int) -> bool:
        return self.table_base <= table <= self.table_base + MAX_PEER_ID


def run(cmd: list[str]) -> subprocess.CompletedProcess:
    """Run a command, never raising (callers decide what a failure means)."""
    try:
        return subprocess.run(cmd, capture_output=True, text=True, check=False)
    except OSError as exc:
        return subprocess.CompletedProcess(cmd, 127, "", str(exc))


def run_ok(cmd: list[str], what: str) -> bool:
    res = run(cmd)
    if res.returncode != 0:
        log.error("%s failed (%s): %s", what, " ".join(cmd), res.stderr.strip())
        return False
    return True


def run_json(cmd: list[str]):
    res = run(cmd)
    if res.returncode != 0:
        log.error("%s failed: %s", " ".join(cmd), res.stderr.strip())
        return None
    try:
        return json.loads(res.stdout or "[]")
    except json.JSONDecodeError as exc:
        log.error("%s: bad JSON: %s", " ".join(cmd), exc)
        return None


def parse_rules(rules) -> set[int]:
    """Tables T that have an `fwmark T lookup T` rule."""
    found: set[int] = set()
    for r in rules or []:
        try:
            table = int(r.get("table", ""))
            mark = int(r.get("fwmark", "0"), 16)
        except ValueError:
            continue
        if mark == table:
            found.add(table)
    return found


def rule_tables(cfg: Config) -> set[int]:
    rules = run_json(["ip", "-4", "-j", "rule", "show"])
    return {t for t in parse_rules(rules) if cfg.owns_table(t)}


def ensure_rule(table: int, have: set[int] | None = None) -> None:
    """Add `fwmark T lookup T` unless present. `have` is a cached listing."""
    if have is None:
        have = parse_rules(run_json(["ip", "-4", "-j", "rule", "show"]))
    if table in have:
        return
    run_ok(
        ["ip", "-4", "rule", "add", "pref", "0", "fwmark", str(table), "table", str(table)],
        f"add rule for table {table}",
    )


def ensure_route(table: int, ifname: str, gateway: str) -> None:
    run_ok(
        [
            "ip",
            "-4",
            "route",
            "replace",
            "default",
            "via",
            "inet6",
            gateway,
            "dev",
            ifname,
            "table",
            str(table),
            "proto",
            ROUTE_PROTO,
        ],
        f"default route via {gateway} ({ifname}) in table {table}",
    )


def nft_elems(cfg: Config, kind: str, name: str) -> list | None:
    """Elements of a named set/map, or None if it can't be read."""
    data = run_json(["nft", "-j", "list", kind, cfg.nft_family, cfg.nft_table, name])
    if data is None:
        return None
    for item in data.get("nftables", []):
        if kind in item:
            return item[kind].get("elem", [])
    return []


def nft_state(cfg: Config) -> tuple[set[int], dict[int, int]] | None:
    marks = nft_elems(cfg, "set", cfg.nft_mark_set)
    ids = nft_elems(cfg, "map", cfg.nft_id_map)
    if marks is None or ids is None:
        return None
    mark_set = {m for m in marks if isinstance(m, int)}
    id_map = {
        e[0]: e[1]
        for e in ids
        if isinstance(e, list) and len(e) == 2 and isinstance(e[0], int) and isinstance(e[1], int)
    }
    return mark_set, id_map


def nft_add(cfg: Config, peers: list[int]) -> None:
    if not peers:
        return
    marks = ", ".join(str(cfg.table(p)) for p in sorted(peers))
    pairs = ", ".join(f"{p} : {cfg.table(p)}" for p in sorted(peers))
    base = ["nft", "add", "element", cfg.nft_family, cfg.nft_table]
    run_ok(base + [cfg.nft_mark_set, "{ " + marks + " }"], "register peer marks with nftables")
    run_ok(base + [cfg.nft_id_map, "{ " + pairs + " }"], "register peer ids with nftables")


def nft_delete(cfg: Config, marks: list[int], ids: list[int], quiet: bool = False) -> None:
    """Remove peers from the nft set/map; quiet deletes one element at a time and ignores failures."""
    base = ["nft", "delete", "element", cfg.nft_family, cfg.nft_table]
    groups = [
        (cfg.nft_id_map, [str(i) for i in ids], "ids"),
        (cfg.nft_mark_set, [str(mark) for mark in marks], "marks"),
    ]
    for target, elements, what in groups:
        if quiet:
            for element in elements:
                run(base + [target, f"{{ {element} }}"])
        elif elements:
            run_ok(
                base + [target, "{ " + ", ".join(elements) + " }"],
                f"deregister peer {what} from nftables",
            )


def ensure_blackhole(table: int) -> None:
    run_ok(
        [
            "ip",
            "-4",
            "route",
            "replace",
            "unreachable",
            "default",
            "table",
            str(table),
            "proto",
            ROUTE_PROTO,
        ],
        f"unreachable default route in table {table}",
    )


def setup_peer(cfg: Config, peer_id: int, ifname: str, gateway: str) -> None:
    table = cfg.table(peer_id)
    ensure_blackhole(table)
    ensure_rule(table)
    nft_add(cfg, [peer_id])
    # Traffic is policy-routed per node, so the reverse path rarely matches.
    try:
        with open(f"/proc/sys/net/ipv4/conf/{ifname}/rp_filter", "w") as f:
            f.write("0")
    except OSError as e:
        log.warning("could not disable rp_filter on %s: %s", ifname, e)
    run_ok(["ip", "link", "set", "dev", ifname, "up"], f"bring up {ifname}")
    ensure_route(table, ifname, gateway)
    log.info("set up peer %d (%s via %s): table/mark %d", peer_id, ifname, gateway, table)


def teardown_peer(cfg: Config, peer_id: int, ifname: str, gateway: str) -> None:
    table = cfg.table(peer_id)
    for _ in range(8):
        if (
            run(["ip", "-4", "rule", "del", "fwmark", str(table), "table", str(table)]).returncode
            != 0
        ):
            break
    run(["ip", "-4", "route", "flush", "table", str(table)])
    nft_delete(cfg, [table], [peer_id], quiet=True)
    log.info("tore down peer %d (%s via %s): table/mark %d", peer_id, ifname, gateway, table)


def live_peers(cfg: Config) -> dict[int, str] | None:
    """peer id -> gateway for every node with a permanent neighbour entry on the device."""
    neighs = run_json(["ip", "-6", "-j", "neigh", "show", "dev", cfg.interface])
    if neighs is None:
        return None
    out: dict[int, str] = {}
    for n in neighs:
        lladdr = n.get("lladdr", "")
        if "PERMANENT" not in n.get("state", []) or not n.get("dst") or len(lladdr) != 2:
            continue
        try:
            pid = int(lladdr, 16)
        except ValueError:
            continue
        if 0 <= pid <= MAX_PEER_ID:
            out[pid] = n["dst"]
    return out


def full_reconcile(cfg: Config, live: dict[int, str]) -> None:
    """Make rules/routes/nft exactly match the set of live nodes."""
    have_rules = rule_tables(cfg)
    for pid, gateway in live.items():
        table = cfg.table(pid)
        ensure_rule(table, have_rules)
        ensure_route(table, cfg.interface, gateway)

    live_tables = {cfg.table(p) for p in live}
    for table in sorted(have_rules - live_tables):
        log.info("gc: stale rule/routes for table %d", table)
        run(["ip", "-4", "rule", "del", "fwmark", str(table), "table", str(table)])
        run(["ip", "-4", "route", "flush", "table", str(table)])

    state = nft_state(cfg)
    if state is None:
        return
    cur_marks, cur_map = state
    want_marks = live_tables
    want_map = {pid: cfg.table(pid) for pid in live}

    stale_ids = [i for i, m in cur_map.items() if want_map.get(i) != m]
    stale_marks = [m for m in cur_marks if cfg.owns_table(m) and m not in want_marks]
    if stale_ids or stale_marks:
        nft_delete(cfg, stale_marks, stale_ids)

    missing = [
        pid for pid in live if cfg.table(pid) not in cur_marks or cur_map.get(pid) != cfg.table(pid)
    ]
    if missing:
        log.info("nft: (re)registering peers %s", sorted(missing))
        nft_add(cfg, missing)


def normalize_prefix(val: str) -> str | None:
    """`1.2.3.4` -> `1.2.3.4/32`, host bits masked; None if not IPv4."""
    try:
        net = ipaddress.ip_network(val.strip(), strict=False)
    except ValueError:
        return None
    if net.version != 4:
        return None
    return str(net)


def vm_routes(cfg: Config) -> set[str] | None:
    routes = run_json(["ip", "-4", "-j", "route", "show"])
    if routes is None:
        return None
    out: set[str] = set()
    for r in routes:
        dst = r.get("dst")
        dev = r.get("dev") or ""
        if not dst or dst == "default" or not dev.startswith(cfg.vm_iface_prefix):
            continue
        norm = normalize_prefix(dst)
        if norm:
            out.add(norm)
    return out


def desired_prefixes(cfg: Config) -> set[str] | None:
    vms = vm_routes(cfg)
    if vms is None:
        return None
    out = set(vms)
    for p in [*cfg.pub_ips, *cfg.extra_routes]:
        norm = normalize_prefix(p)
        if norm:
            out.add(norm)
        else:
            log.warning("ignoring invalid configured prefix %r", p)
    return out


class UnixHTTPConnection(http.client.HTTPConnection):
    def __init__(self, path: str, timeout: float = 5.0):
        super().__init__("localhost", timeout=timeout)
        self._path = path

    def connect(self) -> None:
        sock = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
        sock.settimeout(self.timeout)
        sock.connect(self._path)
        self.sock = sock


def control_post(socket_path: str, endpoint: str, prefix: str) -> bool:
    conn = UnixHTTPConnection(socket_path)
    try:
        conn.request(
            "POST",
            endpoint,
            body=json.dumps({"prefix": prefix}),
            headers={"Content-Type": "application/json"},
        )
        resp = conn.getresponse()
        body = resp.read().decode(errors="replace").strip()
        if resp.status != 200:
            log.error("control API %s %s -> %d: %s", endpoint, prefix, resp.status, body)
            return False
        return True
    except OSError as exc:
        log.warning("control API %s %s: %s", endpoint, prefix, exc)
        return False
    finally:
        conn.close()


@dataclass
class AdvertState:
    advertised: set[str] = field(default_factory=set)
    sock_ident: tuple[int, int] | None = None


def sync_advertisements(cfg: Config, state: AdvertState, desired: set[str]) -> None:
    try:
        st = os.stat(cfg.control_socket)
    except OSError:
        state.advertised.clear()
        state.sock_ident = None
        return

    ident = (st.st_ino, st.st_mtime_ns)
    if ident != state.sock_ident:
        if state.sock_ident is not None:
            log.info("control socket was recreated; re-advertising everything")
        state.advertised.clear()
        state.sock_ident = ident

    for prefix in sorted(desired - state.advertised):
        if not control_post(cfg.control_socket, "/advertise", prefix):
            return
        state.advertised.add(prefix)
        log.info("advertised %s", prefix)
    for prefix in sorted(state.advertised - desired):
        if not control_post(cfg.control_socket, "/withdraw", prefix):
            return
        state.advertised.discard(prefix)
        log.info("withdrew %s", prefix)


def daemon(cfg: Config) -> int:
    stop = threading.Event()
    signal.signal(signal.SIGTERM, lambda *_: stop.set())
    signal.signal(signal.SIGINT, lambda *_: stop.set())

    state = AdvertState()
    known: dict[int, str] = {}
    tick = 0
    log.info("daemon started (node %d, control socket %s)", cfg.node_id, cfg.control_socket)

    while not stop.is_set():
        try:
            live = live_peers(cfg)
            if live is not None:
                if live != known or tick % cfg.full_resync_ticks == 0:
                    full_reconcile(cfg, live)
                known = live

            desired = desired_prefixes(cfg)
            if desired is not None:
                sync_advertisements(cfg, state, desired)
        except Exception:
            log.exception("tick failed")
        tick += 1
        stop.wait(cfg.poll_interval)

    log.info("daemon stopped")
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument(
        "--config", required=True, help="path to the JSON config generated by melinoe-vpn.nix"
    )
    sub = ap.add_subparsers(dest="cmd", required=True)
    for name in ("hook-create", "hook-destroy"):
        p = sub.add_parser(name)
        p.add_argument("peer_id", type=int)
        p.add_argument("ifname")
        p.add_argument("gateway")
    sub.add_parser("daemon")
    args = ap.parse_args(argv)

    logging.basicConfig(level=logging.INFO, format="%(name)s: %(message)s", stream=sys.stderr)
    cfg = Config.load(args.config)

    if args.cmd in ("hook-create", "hook-destroy"):
        if not 0 <= args.peer_id <= MAX_PEER_ID:
            log.error("peer id %d out of range", args.peer_id)
            return 2
        (setup_peer if args.cmd == "hook-create" else teardown_peer)(cfg, args.peer_id, args.ifname, args.gateway)
        return 0
    return daemon(cfg)


if __name__ == "__main__":
    sys.exit(main())
